/**
 * Select the glyph subset for the characters of `text` (deduplicated), ready
 * to hand to buildF2tfPackage. Throws naming every character the library
 * lacks, so a widget with unsupported literals fails at build time instead of
 * hitting the facade's missing-glyph rejection on device.
 */
export function glyphsFor(text: string): Record<string, number[]> {
  const selected: Record<string, number[]> = {};
  const missing: string[] = [];
  for (const character of new Set([...text])) {
    const columns = FONT_5X7[character];
    // Copies, so callers tweaking a glyph cannot corrupt the shared library.
    if (columns) selected[character] = [...columns];
    else missing.push(character);
  }
  if (missing.length > 0) {
    throw new Error(`Font 5x7 has no glyph for ${missing.map((c) => JSON.stringify(c)).join(", ")}.`);
  }
  return selected;
}
