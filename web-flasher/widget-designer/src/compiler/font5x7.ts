// ─────────────────────────────────────────────────────────────────────────────
// The Designer's 5x7 column-bitmap font library for F2TF glyph tables.
//
// Each glyph is five column bytes, left to right; rows live in bits 0..6 with
// bit 0 the TOP row — exactly how the device facade and the SDK oracle sample
// them (`(columns[column] >>> row) & 1`, contract.mjs countOrDraw). Space,
// "-", 0-9, A-Z and "°" are copied verbatim from the flashed weather facade's
// COLUMNS table (experiments/mquickjs-target-facade/contract.mjs) so Designer
// widgets render those characters pixel-identically to the proven weather
// look; the rest come from the same classic 5x7 column font family.
//
// An F2TF asset carries at most 64 glyphs, so packages never embed this whole
// table: glyphsFor() selects the subset a widget's literals actually use.
// ─────────────────────────────────────────────────────────────────────────────

