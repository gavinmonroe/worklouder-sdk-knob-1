/** Portable readable fixture: no host font, ImageMagick, browser, or random mask. */
export function createReadableDemoGlyphAtlas(glyphs) {
  return buildGlyphAtlas({ glyphs, width: 8, height: 12,
    source: "render-v2-events-readable-5x7-v1",
    rasterizeGlyph(glyph, { rowStride }) {
      const pattern = GLYPHS_5X7[glyph];
      if (!pattern) throw new Error(`Readable demo atlas has no bitmap for ${glyph}.`);
      const mask = Buffer.alloc(rowStride * 12);
      pattern.forEach((row, y) => {
        for (let x = 0; x < 5; x += 1) if (row[x] === "1") mask[(y + 2) * rowStride] |= 0x80 >>> (x + 1);
      });
      return mask;
    } });
}
