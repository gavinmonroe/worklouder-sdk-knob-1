#!/usr/bin/env node
/* Host proof for the PSRAM VM-heap claim/hand-off/release state machine.
 *
 * psram-module-src/physical_integration.c cannot be compiled on this host: it
 * asserts `sizeof(void *) == 4` and calls stock ESP32-S3 ROM/IROM entry points
 * through absolute addresses, and this machine has no working 32-bit host
 * target (Apple clang arm64, `cc -m32` fails to link).  Neither verify.mjs nor
 * build-diag-module.mjs ever host-compiles it either.
 *
 * So this proof does not model the functions: it EXTRACTS their exact source
 * text (and the exact constants they use) out of the shipped file at run time
 * and compiles that text against a host model of heap_caps_malloc/free and a
 * host PSRAM arena.  If the shipped source changes, the extraction changes with
 * it.  Two things are substituted, and only two:
 *
 *   - PHYSICAL_PSRAM_BEGIN / PHYSICAL_PSRAM_END become uintptr_t globals
 *     holding the host arena bounds.  The real values are image-derived
 *     (0x3c1d0000, +0x200000) and are separately pinned by a _Static_assert in
 *     the shipped file and by mquickjs-esp32s3-module-loader/verify.mjs:111.
 *   - physical_block is reduced to the three fields these functions touch.
 *
 * Everything the proof actually exercises - the 16-byte align-up over an
 * 8-byte-aligned allocator result, the slack bound, the window range checks,
 * the exact 65,536-byte zeroing (and non-overrun into the slack), the
 * single-claim latch, and free-exactly-once - is the shipped text verbatim.
 *
 * No hardware, serial, or flashing is performed.
 */
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const execute = promisify(execFile);
const here = path.dirname(fileURLToPath(import.meta.url));
const repository = path.resolve(here, "../..");
const moduleSource = path.join(here, "psram-module-src/physical_integration.c");
const admission = path.resolve(here,
  "../mquickjs-esp32s3-resident-integration/f2js_admission.h");
const output = path.join(here, "build-psram-host-proof");
const cc = process.env.CC ?? "cc";

const invariant = (ok, message) => { if (!ok) throw new Error(message); };
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");

/* Take a whole function definition: the signature line through the first line
 * that is exactly "}".  The file is uniformly formatted that way. */
function extractFunction(text, signature) {
  const start = text.indexOf(signature);
  invariant(start >= 0, `Missing function "${signature}" in the module source.`);
  const end = text.indexOf("\n}\n", start);
  invariant(end > start, `Unterminated function "${signature}".`);
  return `${text.slice(start, end + 3)}`;
}

function extractDefine(text, name) {
  const match = new RegExp(`^#define ${name} .*$`, "mu").exec(text);
  invariant(match, `Missing #define ${name}.`);
  return match[0];
}

const source = await readFile(moduleSource, "utf8");
const admissionText = await readFile(admission, "utf8");

const defines = [
  extractDefine(source, "PHYSICAL_CAP_8BIT"),
  extractDefine(source, "PHYSICAL_CAP_SPIRAM"),
  extractDefine(source, "PHYSICAL_HEAP_ALIGN_SLACK"),
  extractDefine(admissionText, "FRAMER_F2JS_HEAP_BYTES"),
].join("\n");
const functions = [
  extractFunction(source, "static void zero_bytes(void *value, size_t bytes)"),
  extractFunction(source, "static int in_psram(const void *pointer, size_t bytes)"),
  extractFunction(source, "static int psram_heap_acquire(physical_block *block)"),
  extractFunction(source, "static void *platform_allocate(void *opaque, size_t bytes)"),
  extractFunction(source, "static void platform_free(void *opaque, void *allocation)"),
].join("\n");

/* Sanity: the extracted text must actually be the PSRAM implementation, not a
 * stale copy of the in-block one. */
invariant(functions.includes("STOCK_HEAP_MALLOC(request, caps)") &&
  functions.includes("block->vm_heap_raw") &&
  !functions.includes("sizeof(block->vm_heap)"),
"Extracted functions are not the PSRAM implementation.");

const driver = `/* GENERATED by psram-heap-host-proof.mjs - do not edit. */
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* --- host substitutions (exactly two) ------------------------------------ */
static uintptr_t host_psram_begin;
static uintptr_t host_psram_end;
#define PHYSICAL_PSRAM_BEGIN host_psram_begin
#define PHYSICAL_PSRAM_END host_psram_end

typedef struct {
    uint8_t heap_claimed;
    uint8_t *vm_heap;
    void *vm_heap_raw;
} physical_block;

/* --- constants lifted verbatim from the shipped sources ------------------ */
${defines}

/* --- host model of the two stock heap entry points ----------------------- */
static uint8_t *arena;
static size_t arena_bytes;
static size_t arena_used;
static size_t model_free_bytes;
static size_t model_largest_bytes;
static int model_return_null;
static int model_return_outside;
static size_t model_misalign;      /* bytes added to the aligned bump result */
static size_t model_tail_offset;   /* force the block near the arena end */
static uint32_t malloc_calls;
static uint32_t free_calls;
static void *last_freed;
static uint8_t outside_block[FRAMER_F2JS_HEAP_BYTES + PHYSICAL_HEAP_ALIGN_SLACK];
static uint32_t last_caps;

static void *host_heap_malloc(size_t bytes, uint32_t caps)
{
    uint8_t *result;
    malloc_calls++;
    last_caps = caps;
    if (model_return_null)
        return NULL;
    if (model_return_outside)
        return outside_block;
    if (model_tail_offset != 0u) {
        result = arena + arena_bytes - model_tail_offset;
        return result;
    }
    arena_used = (arena_used + 15u) & ~(size_t)15u;
    result = arena + arena_used + model_misalign;
    arena_used += bytes + model_misalign + 64u;
    if (arena_used > arena_bytes) { arena_used = 0; return NULL; }
    return result;
}

static void host_heap_free(void *allocation)
{
    free_calls++;
    last_freed = allocation;
}

static size_t host_heap_free_size(uint32_t caps) { (void)caps; return model_free_bytes; }
static size_t host_heap_largest(uint32_t caps) { (void)caps; return model_largest_bytes; }

#define STOCK_HEAP_MALLOC host_heap_malloc
#define STOCK_HEAP_FREE host_heap_free
#define STOCK_HEAP_FREE_SIZE host_heap_free_size
#define STOCK_HEAP_LARGEST host_heap_largest

/* --- exact source under proof -------------------------------------------- */
${functions}
/* --- end exact source ----------------------------------------------------- */

static uint32_t checks;
static uint32_t failures;
static void check(int ok, const char *what)
{
    checks++;
    if (!ok) { failures++; fprintf(stderr, "FAIL: %s\\n", what); }
}

static void reset_model(void)
{
    arena_used = 0u;
    model_free_bytes = 1u << 20;
    model_largest_bytes = 1u << 20;
    model_return_null = 0;
    model_return_outside = 0;
    model_misalign = 0u;
    model_tail_offset = 0u;
    malloc_calls = 0u;
    free_calls = 0u;
    last_freed = NULL;
    last_caps = 0u;
}

static physical_block fresh(void)
{
    physical_block block;
    memset(&block, 0, sizeof(block));
    return block;
}

int main(void)
{
    const size_t request = (size_t)FRAMER_F2JS_HEAP_BYTES + PHYSICAL_HEAP_ALIGN_SLACK;
    physical_block block;
    void *heap;
    size_t i;

    arena_bytes = 2u << 20;
    arena = malloc(arena_bytes);
    if (arena == NULL) return 2;
    memset(arena, 0xa5, arena_bytes);
    host_psram_begin = (uintptr_t)arena;
    host_psram_end = (uintptr_t)arena + arena_bytes;

    /* 1. Happy path over an 8-byte-aligned allocator result. */
    reset_model();
    model_misalign = 8u;
    block = fresh();
    check(psram_heap_acquire(&block) == 1, "acquire: 8-aligned result accepted");
    check(malloc_calls == 1u && free_calls == 0u, "acquire: exactly one malloc, no free");
    check(last_caps == (PHYSICAL_CAP_SPIRAM | PHYSICAL_CAP_8BIT),
          "acquire: requests SPIRAM|8BIT caps");
    check(((uintptr_t)block.vm_heap & 15u) == 0u, "acquire: heap is 16-byte aligned");
    check(block.vm_heap_raw != NULL && (uintptr_t)block.vm_heap >= (uintptr_t)block.vm_heap_raw &&
          (uintptr_t)block.vm_heap - (uintptr_t)block.vm_heap_raw <= PHYSICAL_HEAP_ALIGN_SLACK,
          "acquire: raw pointer retained within the slack");
    check(in_psram(block.vm_heap, FRAMER_F2JS_HEAP_BYTES), "acquire: heap inside the window");
    check(block.heap_claimed == 0u, "acquire: engine latch still clear");
    {
        int zeroed = 1;
        for (i = 0; i < FRAMER_F2JS_HEAP_BYTES; i++)
            if (block.vm_heap[i] != 0u) { zeroed = 0; break; }
        check(zeroed, "acquire: the whole 64 KiB is zeroed");
        check(((uint8_t *)block.vm_heap_raw)[0] == 0xa5u,
              "acquire: bytes before the aligned heap are untouched");
        check(block.vm_heap[FRAMER_F2JS_HEAP_BYTES] == 0xa5u,
              "acquire: bytes after the aligned heap are untouched");
    }

    /* 2. Re-acquire on an already-claimed block is refused without allocating. */
    {
        uint32_t before = malloc_calls;
        check(psram_heap_acquire(&block) == 0, "acquire: refuses a second claim");
        check(malloc_calls == before, "acquire: second claim does not allocate");
    }

    /* 3. Scratch use survives, then platform_allocate re-zeroes and latches. */
    memset(block.vm_heap, 0x5c, 62000u);          /* LZSS/F2TF scratch stand-in */
    check(platform_allocate(&block, FRAMER_F2JS_HEAP_BYTES + 1u) == NULL,
          "allocate: wrong size refused");
    check(block.heap_claimed == 0u, "allocate: wrong size does not latch");
    heap = platform_allocate(&block, FRAMER_F2JS_HEAP_BYTES);
    check(heap == (void *)block.vm_heap, "allocate: hands back the PSRAM heap");
    check(block.heap_claimed == 1u, "allocate: latches the claim");
    {
        int zeroed = 1;
        for (i = 0; i < FRAMER_F2JS_HEAP_BYTES; i++)
            if (((uint8_t *)heap)[i] != 0u) { zeroed = 0; break; }
        check(zeroed, "allocate: clears the scratch before the engine sees it");
    }
    check(platform_allocate(&block, FRAMER_F2JS_HEAP_BYTES) == NULL,
          "allocate: refuses a second claim");

    /* 4. free is exact, once, and idempotent afterwards. */
    check(free_calls == 0u, "free: nothing freed yet");
    platform_free(&block, (void *)((uint8_t *)heap + 16));
    check(free_calls == 0u, "free: foreign pointer is ignored");
    check(block.heap_claimed == 1u, "free: foreign pointer leaves the latch set");
    {
        void *raw = block.vm_heap_raw;
        platform_free(&block, heap);
        check(free_calls == 1u && last_freed == raw,
              "free: releases the exact raw allocator pointer once");
    }
    check(block.vm_heap == NULL && block.vm_heap_raw == NULL && block.heap_claimed == 0u,
          "free: clears the block");
    platform_free(&block, heap);
    check(free_calls == 1u, "free: second call cannot double-free");

    /* 5. Preflight refusals never call the allocator. */
    reset_model();
    model_free_bytes = request - 1u;
    block = fresh();
    check(psram_heap_acquire(&block) == 0 && malloc_calls == 0u,
          "acquire: insufficient free PSRAM refused before allocating");
    reset_model();
    model_largest_bytes = request - 1u;
    block = fresh();
    check(psram_heap_acquire(&block) == 0 && malloc_calls == 0u,
          "acquire: insufficient largest PSRAM block refused before allocating");

    /* 6. A NULL allocator result is refused and frees nothing. */
    reset_model();
    model_return_null = 1;
    block = fresh();
    check(psram_heap_acquire(&block) == 0 && free_calls == 0u,
          "acquire: NULL result refused without freeing");
    check(block.vm_heap == NULL && block.vm_heap_raw == NULL, "acquire: NULL leaves block clean");

    /* 7. An out-of-window result is refused AND returned to the allocator. */
    reset_model();
    model_return_outside = 1;
    block = fresh();
    check(psram_heap_acquire(&block) == 0, "acquire: out-of-window result refused");
    check(free_calls == 1u && last_freed == (void *)outside_block,
          "acquire: out-of-window result is freed");
    check(block.vm_heap == NULL && block.vm_heap_raw == NULL,
          "acquire: out-of-window leaves block clean");

    /* 8. A result whose aligned span would run past the window end is refused. */
    reset_model();
    model_tail_offset = FRAMER_F2JS_HEAP_BYTES;   /* raw + request > window end */
    block = fresh();
    check(psram_heap_acquire(&block) == 0, "acquire: overrunning result refused");
    check(free_calls == 1u, "acquire: overrunning result is freed");

    /* 9. platform_allocate refuses a block that never acquired a heap. */
    block = fresh();
    check(platform_allocate(&block, FRAMER_F2JS_HEAP_BYTES) == NULL,
          "allocate: refuses a heap-less block");
    check(platform_allocate(NULL, FRAMER_F2JS_HEAP_BYTES) == NULL,
          "allocate: refuses a NULL block");
    platform_free(&block, NULL);
    platform_free(NULL, NULL);
    check(1, "free: NULL arguments are inert");

    free(arena);
    printf("{\\"status\\":\\"%s\\",\\"checks\\":%u,\\"failures\\":%u}\\n",
           failures == 0u ? "PASS_PSRAM_HEAP_EXACT_SOURCE" : "FAIL", checks, failures);
    return failures == 0u ? 0 : 1;
}
`;

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
const driverFile = path.join(output, "psram-heap-host-proof.c");
const executable = path.join(output, "psram-heap-host-proof");
await writeFile(driverFile, driver);
await execute(cc, ["-std=c11", "-O1", "-g", "-Wall", "-Wextra", "-Werror",
  "-fsanitize=address,undefined", "-fno-omit-frame-pointer", driverFile,
  "-o", executable], { cwd: repository });
const { stdout } = await execute(executable, [], { cwd: repository, env: {
  ...process.env, ASAN_OPTIONS: "abort_on_error=1", UBSAN_OPTIONS: "halt_on_error=1",
} });
const result = JSON.parse(stdout);
invariant(result.status === "PASS_PSRAM_HEAP_EXACT_SOURCE" && result.failures === 0 &&
  result.checks >= 30, `PSRAM heap host proof failed: ${stdout}`);

const manifest = {
  status: "PASS_PSRAM_HEAP_HOST_PROOF_NO_HARDWARE",
  hardwareTouched: false,
  extractedFrom: { file: path.relative(repository, moduleSource), sha256: sha(source) },
  constantsFrom: [
    { file: path.relative(repository, moduleSource),
      defines: ["PHYSICAL_CAP_8BIT", "PHYSICAL_CAP_SPIRAM", "PHYSICAL_HEAP_ALIGN_SLACK"] },
    { file: path.relative(repository, admission), defines: ["FRAMER_F2JS_HEAP_BYTES"] },
  ],
  extractedFunctions: ["zero_bytes", "in_psram", "psram_heap_acquire",
    "platform_allocate", "platform_free"],
  hostSubstitutions: [
    "PHYSICAL_PSRAM_BEGIN/END become host arena bounds (real values are " +
      "image-derived and pinned by a _Static_assert in the shipped file)",
    "physical_block reduced to heap_claimed, vm_heap, vm_heap_raw",
    "heap_caps_malloc/free/get_free_size/get_largest_free_block are host models",
  ],
  driver: { file: path.relative(repository, driverFile), sha256: sha(driver),
    sanitizers: ["address", "undefined"], warnings: "-Wall -Wextra -Werror" },
  result,
};
await writeFile(path.join(output, "psram-heap-host-proof-manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`);
process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);
